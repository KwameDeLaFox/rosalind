function GutCheckSummary({
  run,
  gutChecks,
}: {
  run: RunState;
  gutChecks: Record<string, GutMark>;
}) {
  const total = run.expectedProfileIds.length;
  const arrived = run.results.length;

  const marks: GutMark[] = run.results
    .map((r) => gutChecks[gutKey(run.id, r.profile_id)])
    .filter((m): m is GutMark => Boolean(m));

  if (arrived === 0) return null;

  if (marks.length === 0) {
    return (
      <p className="mt-3 text-xs text-stone-400">
        Mark each objection above — knew this, or new to me. The point is to
        force the gut-check in the moment of reading.
      </p>
    );
  }

  const newCount = marks.filter((m) => m === "new").length;
  const knewCount = marks.filter((m) => m === "knew").length;

  return (
    <div className="mt-3 text-xs text-stone-600">
      <span className="font-mono uppercase tracking-wider text-stone-500">
        Gut check:
      </span>{" "}
      <span className="font-medium text-emerald-700">{newCount} new</span>
      {" · "}
      <span className="font-medium text-stone-500">{knewCount} knew</span>
      {" · "}
      <span className="text-stone-400">
        {marks.length}/{total} marked
      </span>
    </div>
  );
}

