function hasInputForMode(
  mode: InputKind,
  url: string,
  text: string,
  image: string | null,
): boolean {
  if (mode === "url") return url.trim().length > 0;
  if (mode === "text") return text.trim().length > 0;
  if (mode === "screenshot") return image !== null;
  return false;
}

function buildInputPayload(
  mode: InputKind,
  url: string,
  text: string,
  image: string | null,
): {
  kind: InputKind;
  url?: string;
  text?: string;
  image?: string;
} {
  if (mode === "url") return { kind: "url", url: url.trim() };
  if (mode === "text") return { kind: "text", text };
  if (mode === "screenshot" && image) return { kind: "screenshot", image };
  return { kind: mode };
}

function renderMarkdown(
  runs: RunState[],
  gutChecks: Record<string, GutMark>,
): string {
  const lines: string[] = [];
  lines.push("# Synthetic Page Feedback");
  lines.push("");
  lines.push(
    "> These are synthetic, directional reactions generated by an LLM. They are not real user evidence. Use them to generate hypotheses to test with real people, not to make decisions.",
  );
  lines.push("");

  runs.forEach((run, runIndex) => {
    if (runs.length > 1) {
      lines.push(`## Run ${runIndex + 1}`);
      lines.push("");
    }
    if (run.page_summary.title) {
      lines.push(
        `**Page:** ${run.page_summary.title}${run.page_summary.truncated ? " (truncated)" : ""}`,
      );
      lines.push("");
    }

    lines.push("### Top objections");
    lines.push("");
    run.expectedProfileIds.forEach((profileId) => {
      const r = run.results.find((x) => x.profile_id === profileId);
      const obj = r?.feedback.top_objection?.trim();
      const key = gutKey(run.id, profileId);
      const mark = gutChecks[key];
      const markStr =
        mark === "new" ? " _[NEW]_" : mark === "knew" ? " _[KNEW]_" : "";
      const name = PROFILES.find((p) => p.id === profileId)?.name ?? profileId;
      lines.push(`- **${name}**${markStr}: ${obj ? `"${obj}"` : "—"}`);
    });
    lines.push("");

    lines.push("### Full feedback per profile");
    lines.push("");
    run.expectedProfileIds.forEach((profileId) => {
      const r = run.results.find((x) => x.profile_id === profileId);
      const name = PROFILES.find((p) => p.id === profileId)?.name ?? profileId;
      lines.push(`#### ${name}`);
      lines.push("");
      RUBRIC.forEach((field) => {
        const v = r?.feedback[field.key]?.trim() || "—";
        lines.push(`- **${field.label}**: ${v}`);
      });
      lines.push("");
    });
  });

  return lines.join("\n");
}
