// Pure visual checkbox indicator. No button, no role, no aria — the
// parent row carries role="checkbox" and aria-checked. The shadcn
// Checkbox renders as a radix button with role="checkbox" which
// duplicates the row's role in the aria tree; this div avoids that
// while keeping the same look. pointer-events: none is belt-and-
// braces — clicks should already land on the row.
function CheckboxVisual({ checked }: { checked: boolean }) {
  return (
    <div
      aria-hidden="true"
      className={cn(
        "mt-0.5 flex h-4 w-4 shrink-0 items-center justify-center rounded-[4px] border transition-colors pointer-events-none",
        checked
          ? "border-stone-900 bg-stone-900 text-stone-50"
          : "border-stone-300 bg-white",
      )}
    >
      {checked && <Check className="h-3.5 w-3.5" strokeWidth={3} />}
    </div>
  );
}

