function ObjectionCard({
  runId,
  result,
  gutChecks,
  onGutCheck,
}: {
  runId: number;
  result: ProfileResult;
  gutChecks: Record<string, GutMark>;
  onGutCheck: (runId: number, profileId: ProfileId, value: GutMark) => void;
}) {
  const profile = PROFILES.find((p) => p.id === result.profile_id);
  if (!profile) return null;
  const obj = result.feedback.top_objection?.trim();
  const key = gutKey(runId, result.profile_id);
  const mark = gutChecks[key];

  return (
    <div
      className={cn(
        "flex flex-col gap-3 rounded-lg border bg-white p-4 transition-colors",
        "animate-in fade-in slide-in-from-bottom-2 duration-300",
        mark === "new" && "border-emerald-400 bg-emerald-50",
        mark === "knew" && "border-stone-200 bg-stone-50 opacity-75",
        !mark && "border-stone-200",
      )}
    >
      <div className="flex items-baseline justify-between gap-2">
        <h4 className="text-sm font-semibold text-stone-900">
          {result.profile_name}
        </h4>
        {mark && (
          <span
            className={cn(
              "text-[11px] font-mono uppercase tracking-wider",
              mark === "new" ? "text-emerald-700" : "text-stone-500",
            )}
          >
            {mark === "new" ? "New" : "Knew"}
          </span>
        )}
      </div>
      {obj ? (
        <p className="flex-1 border-l-2 border-amber-600 pl-3 text-base text-stone-900">
          {obj.startsWith('"') && obj.endsWith('"') ? obj : `"${obj}"`}
        </p>
      ) : (
        <p className="flex-1 text-sm italic text-stone-400">
          No objection returned.
        </p>
      )}
      <div className="flex gap-2 border-t border-stone-100 pt-2">
        <GutCheckButton
          active={mark === "new"}
          onClick={() => onGutCheck(runId, result.profile_id, "new")}
          activeClass="border-emerald-600 bg-emerald-600 text-white"
        >
          <Lightbulb className="h-3.5 w-3.5" />
          New to me
        </GutCheckButton>
        <GutCheckButton
          active={mark === "knew"}
          onClick={() => onGutCheck(runId, result.profile_id, "knew")}
          activeClass="border-stone-700 bg-stone-700 text-white"
        >
          <Eye className="h-3.5 w-3.5" />
          Knew this
        </GutCheckButton>
      </div>
    </div>
  );
}

